"""Generate docs/reference.md from the docstrings.

The package (src/mossaudit) is documented in full: modules, classes and public functions. The
benchmark and script files are command-line tools, so only their module docstring (what they do and
how to run them) is included.

It parses the source with `ast` (nothing is imported or run), so it needs no credentials and no
extra dependency. Private names (leading underscore) are skipped.

Run:  python scripts/gen_api_docs.py
"""

from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = sorted((ROOT / "src/mossaudit").glob("*.py"))
COMMANDS = [*sorted((ROOT / "benchmarks").glob("*/*.py")), *sorted((ROOT / "scripts").glob("*.py"))]
OUT = ROOT / "docs/reference.md"


def _signature(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    args = ast.unparse(fn.args)
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    prefix = "async " if isinstance(fn, ast.AsyncFunctionDef) else ""
    return f"{prefix}{fn.name}({args}){ret}"


def _doc(node: ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    return (ast.get_docstring(node) or "").strip()


def _function(fn: ast.FunctionDef | ast.AsyncFunctionDef, level: str) -> list[str]:
    lines = [f"{level} `{_signature(fn)}`", ""]
    if doc := _doc(fn):
        lines += [doc, ""]
    return lines


def _module(path: Path, full: bool = True) -> list[str]:
    tree = ast.parse(path.read_text())
    rel = path.relative_to(ROOT).as_posix()
    lines = [f"### `{rel}`" if not full else f"## `{rel}`", ""]
    if doc := _doc(tree):
        lines += [doc if full else f"```\n{doc}\n```", ""]
    if not full:
        return lines
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            lines += [f"### class `{node.name}`", ""]
            if doc := _doc(node):
                lines += [doc, ""]
            for item in node.body:
                if (isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef))
                        and (not item.name.startswith("_") or item.name == "__init__")):
                    lines += _function(item, "####")
        elif (isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
              and not node.name.startswith("_")):
            lines += _function(node, "###")
    return lines


def main() -> None:
    lines = ["# Code reference", "",
             "Generated by `python scripts/gen_api_docs.py` from the docstrings. Do not edit by hand.",
             ""]
    for path in PACKAGE:
        if path.name != "__init__.py":
            lines += _module(path)
    lines += ["## Commands", "", "Benchmarks and scripts, with the usage text from each file.", ""]
    for path in COMMANDS:
        lines += _module(path, full=False)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines).rstrip() + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(PACKAGE) + len(COMMANDS)} files scanned)")


if __name__ == "__main__":
    main()
